// Définitions de forme des 11 véhicules (voir body.js pour le générateur).
// t = abscisse normalisée le long de la voiture (0 = nez, 1 = poupe) ; hauteurs en mètres ;
// `plan` = demi-largeur en fraction de la demi-largeur catalogue ; 's' = arête vive.
// Décalcomanies : p = projection ('front' | 'rear' | 'side' | 'top'), coordonnées dans le plan de projection
// (face avant/arrière : x,y ; côté : z,y ; dessus : x,z), m:'light' pour une optique (ch = canal lumineux).
import { CH } from './materials.js';

const bot = (c, nose, tail, f = 0.05, r = 0.05) => [[0, nose], [0.015, c + (nose - c) * 0.35], [f, c + 0.012], [f + 0.07, c], [1 - r - 0.07, c], [1 - r, c + 0.02], [0.985, c + (tail - c) * 0.4], [1, tail]];

// couleurs d'optiques
const LENS = 0x060708, LED = 0xe6efff, RED = 0x9a0c10, AMBER = 0xd9730a, WHITE = 0xd8dde2;
const lens = (p, shape, extra = {}) => ({ p, ...shape, c: LENS, r: 0.1, mt: 0, lift: 0.009, ...extra });
const head = (shape, extra = {}) => ({ p: 'front', m: 'light', ch: CH.HEAD, c: LED, lift: 0.014, ...shape, ...extra });
const drl = (shape, extra = {}) => ({ p: 'front', m: 'light', ch: CH.DRL, c: LED, lift: 0.014, ...shape, ...extra });
const tail = (shape, extra = {}) => ({ p: 'rear', m: 'light', ch: CH.TAIL, c: RED, lift: 0.011, ...shape, ...extra });
const brake = (shape, extra = {}) => ({ p: 'rear', m: 'light', ch: CH.BRAKE, c: RED, lift: 0.011, ...shape, ...extra });
const rev = (shape, extra = {}) => ({ p: 'rear', m: 'light', ch: CH.REVERSE, c: WHITE, lift: 0.014, ...shape, ...extra });
const blinkF = (shape, extra = {}) => ({ p: 'front', m: 'light', ch: 'blink', c: AMBER, lift: 0.015, ...shape, ...extra });
const blinkR = (shape, extra = {}) => ({ p: 'rear', m: 'light', ch: 'blink', c: AMBER, lift: 0.015, ...shape, ...extra });
// troisième feu stop : fine barrette en haut de la lunette arrière (projetée par le dessus)
const chmsl = (z, w = 0.42) => ({ p: 'top', m: 'light', ch: CH.BRAKE, c: RED, lift: 0.012, rect: [0, z, w, 0.03], center: true, sub: [6, 1] });
const dark = (p, shape, extra = {}) => ({ p, ...shape, c: 0x040404, r: 0.7, ...extra });
const chrome = (p, shape, extra = {}) => ({ p, ...shape, c: 0xd0d3d6, r: 0.12, mt: 1, ...extra });

